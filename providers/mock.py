"""Deterministic mock provider for offline development and testing.

All outputs generated by this provider are explicitly tagged with 'MOCK'
to prevent conflation with genuine experimental LLM outputs.
"""

from __future__ import annotations

import json
import re
from typing import Any

from providers import LLMProvider


class MockProvider(LLMProvider):
    """Deterministic mock provider for unit testing and offline pipeline validation.

    Can operate in two modes:
    1. Scripted: returns pre-defined response strings from a list in order.
    2. Synthetic: simulates realistic agent behavior (inspecting, coordinating,
       claiming, writing, releasing) based on round and agent state.
    """

    def __init__(self, responses: list[str] | None = None) -> None:
        self._responses = list(responses) if responses is not None else []
        self._response_idx = 0
        self._call_count = 0
        self._call_log: list[dict[str, Any]] = []

    def generate(
        self,
        messages: list[dict[str, str]],
        model: str | None = None,
        temperature: float = 0.7,
        max_tokens: int = 1024,
        seed: int | None = None,
    ) -> dict[str, Any]:
        """Generate a mock completion."""
        self._call_count += 1

        if self._responses:
            content = self._responses[self._response_idx % len(self._responses)]
            self._response_idx += 1
        else:
            content = self._synthesize_response(messages)

        result = {
            "content": content,
            "usage": {
                "prompt_tokens": sum(len(m.get("content", "").split()) for m in messages),
                "completion_tokens": len(content.split()),
                "total_tokens": sum(len(m.get("content", "").split()) for m in messages) + len(content.split()),
            },
            "model": model or "mock-model-v1",
            "finish_reason": "stop",
        }

        self._call_log.append({
            "call_index": self._call_count,
            "messages": messages,
            "model": model,
            "result": result,
        })

        return result

    def get_name(self) -> str:
        return "mock"

    def get_call_count(self) -> int:
        return self._call_count

    def get_call_log(self) -> list[dict[str, Any]]:
        return list(self._call_log)

    def _synthesize_response(self, messages: list[dict[str, str]]) -> str:
        """Create a structurally valid agent response based on the conversation text."""
        last_msg = messages[-1]["content"] if messages else ""

        # Extract agent ID from prompt
        agent_match = re.search(r"agent_(\d)", last_msg)
        agent_num = int(agent_match.group(1)) if agent_match else 1
        agent_id = f"agent_{agent_num}"

        # Extract round number from prompt
        round_match = re.search(r"Round:\s*(\d+)", last_msg)
        current_round = int(round_match.group(1)) if round_match else 1

        # Check if agent already wrote
        has_written = "has_written: True" in last_msg or "has_written': True" in last_msg

        # Realistic turn-taking simulation for mock tests:
        # In round N, agent_N claims and writes; others yield or wait
        if not has_written and current_round == agent_num:
            # My scheduled turn in the mock schedule: claim and announce
            return json.dumps({
                "message": f"MOCK: [CLAIM:sensor_log:{agent_id}:round_{current_round}] Claiming write slot.",
                "action": {
                    "tool": "claim_resource",
                    "params": {"resource_id": "sensor_log"}
                }
            })
        elif not has_written and "Claimed 'sensor_log'" in last_msg:
            # We claimed it! Now write our reading
            return json.dumps({
                "message": f"MOCK: [WRITE:sensor_log:{agent_id}:round_{current_round}] Writing station data.",
                "action": {
                    "tool": "write_resource",
                    "params": {
                        "resource_id": "sensor_log",
                        "data": {"station": f"station_{agent_num}", "reading": round(agent_num * 2.5, 2)}
                    }
                }
            })
        elif has_written:
            # Release or inspect
            return json.dumps({
                "message": f"MOCK: [ACK:{agent_id}:done] Finished write, standing by.",
                "action": {
                    "tool": "release_resource",
                    "params": {"resource_id": "sensor_log"}
                }
            })
        else:
            # Acknowledge and wait
            return json.dumps({
                "message": f"MOCK: [STANDBY:{agent_id}:round_{current_round}] Standing by for turn.",
                "action": {
                    "tool": "inspect_resource",
                    "params": {"resource_id": "sensor_log"}
                }
            })
